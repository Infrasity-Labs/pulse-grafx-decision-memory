"""Publish the word overlap between each question and the decision that answers it.

The questions were meant to avoid the wording of the decision titles. This script measures it instead of asserting it.
For every answerable question it compares the question's content words with the words of the expected decision's node text
(title, content and reason):
  exact overlap   share of the question's content words that appear as the same word in the node
  prefix overlap  the same, after cutting every word to its first 5 letters, so favourite and favorites count as one
It also shows how many other decisions overlap more than the expected one (rank 1 means no other decision shares more words).

  python scripts/question_overlap.py                print the table
  python scripts/question_overlap.py --write        write demo-state/arms/question-overlap.json and docs/QUESTIONS.md
  python scripts/question_overlap.py --check        exit 1 if either file differs from what the script computes
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import corpus  # noqa: E402
from lexical_baseline import tokens  # noqa: E402

JSON_OUT = ROOT / "demo-state" / "arms" / "question-overlap.json"
MD_OUT = ROOT / "docs" / "QUESTIONS.md"


def _cut(words: set[str]) -> set[str]:
    return {w[:5] for w in words}


def compute() -> dict:
    nodes = {d["slug"]: set(tokens(corpus.node_text(d))) for d in corpus.all_decisions()}
    rows = []
    for q in corpus.questions():
        qw = set(tokens(q["text"]))
        row = {"id": q["id"], "split": q["split"], "kind": q["kind"], "expected_slug": q["expected_slug"], "question_words": len(qw)}
        if q["expected_slug"]:
            nw = nodes[q["expected_slug"]]
            shared = sorted(qw & nw)
            row["shared_words"] = shared
            row["exact_overlap"] = round(len(shared) / len(qw), 2) if qw else 0.0
            row["prefix_overlap"] = round(len(_cut(qw) & _cut(nw)) / len(_cut(qw)), 2) if qw else 0.0
            more = sum(1 for s, w in nodes.items() if s != q["expected_slug"] and len(qw & w) > len(shared))
            row["decisions_sharing_more_words"] = more
        rows.append(row)
    summary = {}
    for split in ("dev", "held_out", "model_authored", "legacy"):
        rs = [r for r in rows if r["split"] == split and r["expected_slug"]]
        summary[split] = {
            "answerable_questions": len(rs),
            "mean_exact_overlap": round(sum(r["exact_overlap"] for r in rs) / len(rs), 2),
            "mean_prefix_overlap": round(sum(r["prefix_overlap"] for r in rs) / len(rs), 2),
            "max_exact_overlap": max(r["exact_overlap"] for r in rs),
            "questions_with_no_shared_word": sum(1 for r in rs if not r["shared_words"]),
            "expected_decision_has_most_shared_words": sum(1 for r in rs if r["decisions_sharing_more_words"] == 0),
        }
    return {"method": "content words after the stop word list in scripts/lexical_baseline.py; exact words and 5-letter prefixes", "summary": summary, "rows": rows}


def render_md(res: dict) -> str:
    lines = [
        "# Questions and their word overlap",
        "",
        "Generated by [`scripts/question_overlap.py`](../scripts/question_overlap.py). Do not edit by hand. A test fails if this file drifts.",
        "",
        "The questions in splits `dev` and `held_out` were written after the 32-decision board existed, by an assistant model, not by the Recorder model and not by a person. They were meant to avoid the wording of the decision titles. The table measures how well that worked. `legacy` is the original ten questions. Split `model_authored` was written by claude-haiku-5-5, a different model from the agent model, from the decision texts only; it is scored separately and a person has not reviewed it (see `corpus/questions-model-authored.json`).",
        "",
        "Overlap is the share of a question's content words that also appear in the node text of the decision that answers it. Exact compares whole words. Prefix compares the first 5 letters, so `favourite` and `favorites` count as one word. \"Rank 1\" means no other decision shares more words with the question.",
        "",
        "History of the held-out set: five held-out questions (h1, h6, h9, h10, h11) were reworded once. Their first wording shared up to 71 percent of its content words with the answering decision, and the lexical baseline had scored 7 of 11 on the held-out answerable questions with that wording. They were reworded to lower the overlap, after that lexical run and before any Pulse retrieval run or agent run. The first wording is not kept. The table below is for the final wording.",
        "",
        "## Summary per split",
        "",
        "| Split | Answerable | Mean exact | Mean prefix | Max exact | No shared word | Expected decision shares the most words |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for split, s in res["summary"].items():
        lines.append(f"| {split} | {s['answerable_questions']} | {s['mean_exact_overlap']} | {s['mean_prefix_overlap']} | {s['max_exact_overlap']} | "
                     f"{s['questions_with_no_shared_word']} | {s['expected_decision_has_most_shared_words']} of {s['answerable_questions']} |")
    lines += ["", "## Every question", "", "| Id | Split | Kind | Expected decision | Exact | Prefix | Other decisions sharing more words | Shared words | Question |", "|---|---|---|---|---:|---:|---:|---|---|"]
    qtext = {q["id"]: q["text"] for q in corpus.questions()}
    for r in res["rows"]:
        if r["expected_slug"]:
            lines.append(f"| {r['id']} | {r['split']} | {r['kind']} | `{r['expected_slug']}` | {r['exact_overlap']} | {r['prefix_overlap']} | {r['decisions_sharing_more_words']} | "
                         f"{', '.join(r['shared_words']) or 'none'} | {qtext[r['id']]} |")
        else:
            lines.append(f"| {r['id']} | {r['split']} | {r['kind']} | none | n/a | n/a | n/a | n/a | {qtext[r['id']]} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args()
    res = compute()
    js, md = json.dumps(res, indent=2) + "\n", render_md(res)
    if a.write:
        JSON_OUT.parent.mkdir(parents=True, exist_ok=True)
        JSON_OUT.write_text(js)
        MD_OUT.write_text(md)
        print(f"wrote {JSON_OUT.relative_to(ROOT)} and {MD_OUT.relative_to(ROOT)}")
        return 0
    if a.check:
        stale = [p.name for p, t in ((JSON_OUT, js), (MD_OUT, md)) if not p.exists() or p.read_text() != t]
        print("question overlap files match the script" if not stale else f"stale: {', '.join(stale)}. Run: python scripts/question_overlap.py --write")
        return 1 if stale else 0
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
